    const book68 = library["age-6-8"][current6_8];
    if (book68) {
        document.getElementById("bookImage-6-8").src = book68.image;
        document.getElementById("title-6-8").innerHTML = book68.title;
        document.getElementById("author-6-8").innerHTML = book68.author;
        document.getElementById("description-6-8").innerHTML = book68.description;
    }

    const book1012 = library["age-10-12"][current10_12];
    if (book1012) {
        document.getElementById("bookImage-10-12").src = book1012.image;
        document.getElementById("title-10-12").innerHTML = book1012.title;
        document.getElementById("author-10-12").innerHTML = book1012.author;
        document.getElementById("description-10-12").innerHTML = book1012.description;
    }
